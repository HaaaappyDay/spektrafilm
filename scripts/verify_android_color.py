#!/usr/bin/env python3
"""Independent mobile math/fixture generator and direct-model approximation report.

Uses float64 NumPy interpolation, not the LUT creator's interpolation helper.
Run --presets DIR --out DIR [--approximation] after build_android_presets.py.
"""
from __future__ import annotations

import argparse
import hashlib
import itertools
import json
from pathlib import Path
import numpy as np


def decode_srgb(x):
    x = np.asarray(x, dtype=np.float64)
    return np.where(x <= .04045, x / 12.92, ((x + .055) / 1.055) ** 2.4)


def encode_srgb(x):
    x = np.clip(np.asarray(x, dtype=np.float64), 0, 1)
    return np.where(x <= .0031308, 12.92 * x, 1.055 * x ** (1 / 2.4) - .055)


def sample_cube(table, rgb, domain_min=(0, 0, 0), domain_max=(1, 1, 1)):
    table, rgb = np.asarray(table), np.asarray(rgb, dtype=np.float64)
    size = table.shape[0]
    low, high = np.asarray(domain_min), np.asarray(domain_max)
    if table.shape != (size, size, size, 3) or size < 2 or not np.all(high > low):
        raise ValueError('Invalid cube/domain')
    pos = np.clip((rgb - low) / (high - low), 0, 1) * (size - 1)
    lo = np.floor(pos).astype(int)
    hi = np.minimum(lo + 1, size - 1)
    frac = pos - lo
    result = np.zeros_like(pos)
    for r, g, b in itertools.product((0, 1), repeat=3):
        xyz = np.where([r, g, b], hi, lo)
        weight = np.prod(np.where([r, g, b], frac, 1 - frac), axis=-1)
        result += table[xyz[..., 2], xyz[..., 1], xyz[..., 0]] * weight[..., None]
    return result


def transform(rgb, table, strength, exposure_ev, temperature):
    params = np.array([strength, exposure_ev, temperature])
    if not np.all(np.isfinite(params)) or not 0 <= strength <= 1 or not -2 <= exposure_ev <= 2 or not -100 <= temperature <= 100:
        raise ValueError('Invalid edit parameters')
    t = temperature / 100
    corrected = np.clip(decode_srgb(rgb) * np.array([2**(.25*t), 1, 2**(-.25*t)]) * 2**exposure_ev, 0, 1)
    film = np.clip(sample_cube(table, encode_srgb(corrected)), 0, 1)
    return encode_srgb((1 - strength) * corrected + strength * decode_srgb(film))


def reference_pixels():
    rng = np.random.default_rng(7639)
    gray = np.repeat(np.arange(256, dtype=np.uint8)[:, None], 3, axis=1)
    corners = np.array(list(itertools.product((0, 255), repeat=3)), dtype=np.uint8)
    near = np.array(list(itertools.product((0, 1, 2, 10, 11, 12, 127, 128, 253, 254, 255), repeat=3)), dtype=np.uint8)
    values = np.concatenate((corners, gray, near, rng.integers(0, 256, (512, 3), dtype=np.uint8)))
    # Asymmetric rows expose flips, width alignment and tile-boundary mistakes.
    width = 43
    values = np.concatenate((values, np.zeros(((-len(values)) % width, 3), dtype=np.uint8)))
    return values.reshape(-1, width, 3)


def load_presets(path):
    from spektrafilm_lut_creator.formats import get_format
    manifest = json.loads((path / 'manifest.json').read_text())
    for preset in manifest['presets']:
        cube_path = path / Path(preset['assetPath']).name
        if hashlib.sha256(cube_path.read_bytes()).hexdigest() != preset['sha256']:
            raise ValueError('Preset SHA256 mismatch')
        yield preset, get_format('cube').read(cube_path)


def rgba_bytes(rgb):
    rgb = np.floor(np.clip(rgb, 0, 1) * 255 + .5).astype(np.uint8)
    return np.concatenate((rgb, np.full((*rgb.shape[:-1], 1), 255, dtype=np.uint8)), axis=-1).tobytes()


def generate_fixtures(presets: Path, out: Path):
    out.mkdir(parents=True, exist_ok=True)
    pixels = reference_pixels()
    data = {'schemaVersion': 1, 'seed': 7639, 'width': pixels.shape[1], 'height': pixels.shape[0], 'cases': []}
    (out / 'input.rgba').write_bytes(rgba_bytes(pixels / 255))
    for preset, cube in load_presets(presets):
        for strength, ev, temperature in itertools.product((0, .5, 1), (-2, 0, 2), (-100, 0, 100)):
            name = f"{preset['id']}-s{strength}-e{ev}-t{temperature}.rgba"
            output = rgba_bytes(transform(pixels / 255, cube.table, strength, ev, temperature))
            (out / name).write_bytes(output)
            data['cases'].append({'presetId': preset['id'], 'strength': strength, 'exposureEv': ev,
                                  'temperature': temperature, 'expected': name,
                                  'sha256': hashlib.sha256(output).hexdigest()})
    (out / 'reference.json').write_text(json.dumps(data, indent=2) + '\n')
    (out / 'README.md').write_text('Original deterministic synthetic RGBA8 patches, seed7639.\n'
        'Generated by scripts/verify_android_color.py using independent float64 NumPy math and committed cubes.\n'
        'Input: corners, all256 gray codes, near endpoints/transfer knees and512 random colors, asymmetric43px rows.\n'
        'Expected: all27 strength/EV/temperature combinations for each of three films; alpha255; round half up.\n'
        'No photographs. Source GPLv3; film-derived outputs retain the presets/LICENSE.txt terms and attribution.\n')


def approximate(presets: Path, out: Path):
    """Evaluate direct physics at off-grid points; never sample a second LUT as truth."""
    from build_android_presets import make_spec
    from spektrafilm.runtime.params_builder import init_params, digest_params
    from spektrafilm.runtime.pipeline import SimulationPipeline
    from spektrafilm_lut_creator.color_spaces import get, decode_cctf, encode_cctf, input_exposure_gain, output_midgray_gain
    import colour
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    out.mkdir(parents=True, exist_ok=True)
    gray = np.repeat(np.linspace(0, 1, 1024)[:, None], 3, axis=1)
    samples = np.concatenate((reference_pixels().reshape(-1, 3) / 255,
                              np.random.default_rng(19103).random((4096, 3)), gray))
    report = {'schemaVersion': 1, 'sampleCount': len(samples), 'seed': 19103,
              'meaning': '33^3 LUT versus same deterministic direct pipeline, not GPU implementation error',
              'presets': []}
    for preset, cube in load_presets(presets):
        spec = make_spec(preset['id'])
        params = init_params(film_profile=spec.film_profile, print_profile=spec.print_profiles[0])
        params.debug.lut_mode = True
        params.io.input_color_space = get(spec.input_color_space).primaries
        params.io.output_color_space = get(spec.output_color_space).primaries
        params.io.input_cctf_decoding = params.io.output_cctf_encoding = False
        params.io.input_gamut_compress = spec.input_gamut_compress
        params.io.output_gamut_compress = spec.output_gamut_compress
        pipeline = SimulationPipeline(digest_params(params))
        linear = (decode_cctf(samples, spec.input_color_space) * input_exposure_gain(spec.input_color_space, spec.stops_above_midgray)).astype(np.float32)
        direct = pipeline.process(linear.reshape(1, -1, 3), inject='rgb_in', collect='rgb_out')
        direct = np.clip(encode_cctf(np.asarray(direct) * output_midgray_gain(spec.output_color_space), spec.output_color_space), 0, 1).reshape(-1, 3)
        approx = sample_cube(cube.table, samples, cube.domain_min, cube.domain_max)
        error = np.abs(approx - direct) * 255
        delta = colour.delta_E(colour.XYZ_to_Lab(colour.sRGB_to_XYZ(approx)),
                               colour.XYZ_to_Lab(colour.sRGB_to_XYZ(direct)), method='CIE 2000')
        worst = np.argsort(error.max(axis=1))[-10:][::-1]
        stats = lambda x: {'mean': float(np.mean(x)), 'p95': float(np.percentile(x, 95)), 'max': float(np.max(x))}
        report['presets'].append({'id': preset['id'], 'rgbCodeError': stats(error), 'deltaE2000': stats(delta),
            'worstSamples': [{'input': samples[i].tolist(), 'lut': approx[i].tolist(), 'direct': direct[i].tolist(),
                              'maxCodeError': float(error[i].max()), 'deltaE2000': float(delta[i])} for i in worst]})
        figure, axes = plt.subplots(2, 1, figsize=(8, 6), layout='constrained')
        for c, color in enumerate(('r', 'g', 'b')):
            axes[0].plot(gray[:, 0], direct[-1024:, c], color=color, label=f'direct {color}')
            axes[0].plot(gray[:, 0], approx[-1024:, c], color=color, linestyle='--', label=f'LUT {color}')
            axes[1].plot(gray[:, 0], (approx[-1024:, c] - direct[-1024:, c]) * 255, color=color)
        axes[0].set(title=preset['displayName'] + ' — gray ramp', ylabel='Encoded output')
        axes[0].legend(ncol=3); axes[1].set(xlabel='Encoded input', ylabel='LUT − direct, RGB codes')
        figure.savefig(out / (preset['id'] + '-approximation.png'), dpi=140)
        plt.close(figure)
        print(preset['id'], report['presets'][-1]['rgbCodeError'], report['presets'][-1]['deltaE2000'], flush=True)
    (out / 'approximation.json').write_text(json.dumps(report, indent=2) + '\n')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--presets', type=Path, required=True)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--approximation', action='store_true')
    args = parser.parse_args()
    if args.approximation:
        approximate(args.presets, args.out)
    else:
        generate_fixtures(args.presets, args.out)
