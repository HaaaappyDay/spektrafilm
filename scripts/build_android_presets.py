#!/usr/bin/env python3
"""Bake committed mobile presets; writes artifacts only under --out.

python scripts/build_android_presets.py --out android/app/src/main/assets/presets
Requires Python 3.13 and the project's dependencies, never invoked by Gradle.

The original Portra 400, Gold 200, and Ektar 100 cubes are kept byte-for-byte.
Missing stocks are baked. Reversal stocks are scanned, matching the GUI.
"""
from __future__ import annotations

import argparse
from dataclasses import asdict
import hashlib
import importlib.metadata
import json
from pathlib import Path
import platform
import shutil
import subprocess
import tempfile
import re

from spektrafilm.model.stocks import FilmStocks
from spektrafilm_lut_creator.bundles import BundleSpec
from spektrafilm_lut_creator.builders import BundleBuilder

ROOT = Path(__file__).resolve().parents[1]
PRESERVED_IDS = ('kodak_portra_400', 'kodak_gold_200', 'kodak_ektar_100')
PRESERVED_COMMIT = 'f37a1604c24abe60d14731754fc0d36abcb2e238'
REVERSAL_PRINT = 'reversal-scan'
CARRIER_PRINT = 'kodak_portra_endura'
ATTRIBUTION = 'Generated from spektrafilm by Andrea Volpato and contributors; https://github.com/andreavolpato/spektrafilm. See LICENSE.txt.'
CATALOG_KT = ROOT / 'android/app/src/main/java/io/github/haaaappyday/filmeditor/render/ShippedFilmCatalog.kt'


def film_records() -> list[dict]:
    """Every camera stock, with the three original films listed first."""
    from importlib.resources import files

    records = []
    for stock in FilmStocks:
        info = json.loads(files('spektrafilm.data.profiles').joinpath(f'{stock.value}.json').read_text())['info']
        positive = info['type'] == 'positive'
        target = info.get('target_print')
        if positive:
            if target:
                raise ValueError(f'{stock.value} is reversal but names a print')
            paired, bake_print = REVERSAL_PRINT, CARRIER_PRINT
        else:
            if not target:
                raise ValueError(f'{stock.value} has no target print')
            paired = bake_print = target
        records.append({'id': stock.value, 'display_name': info['name'], 'print_profile': paired,
                        'bake_print': bake_print, 'scan_film': positive})
    first = {film: index for index, film in enumerate(PRESERVED_IDS)}
    enum_index = {stock.value: index for index, stock in enumerate(FilmStocks)}
    records.sort(key=lambda record: (0, first[record['id']]) if record['id'] in first else (1, enum_index[record['id']]))
    return records


PRESETS = {record['id']: record['display_name'] for record in film_records()}


def make_spec(film: str) -> BundleSpec:
    record = next(item for item in film_records() if item['id'] == film)
    return BundleSpec(
        film_profile=film, print_profiles=(record['bake_print'],),
        input_color_space='sRGB', output_color_space='sRGB', topology='1lut',
        resolution=33, stops_above_midgray=None, qa=True,
    )


def write_catalog(records: list[dict] | None = None) -> None:
    records = records or film_records()
    prints = '\n'.join(f'        "{record["id"]}" to "{record["print_profile"]}",' for record in records)
    names = '\n'.join(
        '        "{}" to "{}",'.format(record['id'], record['display_name'].replace('\\', '\\\\').replace('"', '\\"'))
        for record in records)
    CATALOG_KT.write_text(
        'package io.github.haaaappyday.filmeditor.render\n\n'
        '/** Generated by scripts/build_android_presets.py. Keep print pairings with the asset manifest. */\n'
        'internal object ShippedFilmCatalog {\n'
        f'    const val REVERSAL_SCAN = "{REVERSAL_PRINT}"\n'
        '    val printById: Map<String, String> = linkedMapOf(\n'
        f'{prints}\n'
        '    )\n'
        '    val displayNames: Map<String, String> = linkedMapOf(\n'
        f'{names}\n'
        '    )\n'
        '}\n'
    )


def _sha256(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _bake(record: dict, out: Path, cube: Path) -> None:
    spec = make_spec(record['id'])
    builder = BundleBuilder(spec)
    bundle = builder.build()
    report_dir = out / 'bake-reports' / record['id']
    report_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.bake-', dir=out) as work:
        bundle_dir = Path(work)
        builder.write(bundle, bundle_dir)
        shutil.copyfile(bundle_dir / bundle.luts[0][0], cube)
        shutil.copyfile(bundle_dir / 'bundle.json', report_dir / 'bundle.json')
        for report in (bundle_dir / 'qa').rglob('report.md'):
            text = re.sub(r'^!\[.*?\]\(.*?\)\s*$', '', report.read_text(), flags=re.MULTILINE)
            (report_dir / 'report.md').write_text(text + '\nQA figures omitted from mobile assets; all numerical results retained.\n')


def build(out: Path) -> dict:
    out = out.resolve()
    out.mkdir(parents=True, exist_ok=True)
    records = film_records()
    write_catalog(records)
    manifest = {
        'schemaVersion': 1,
        'engineCommit': subprocess.check_output(['git', 'rev-parse', 'HEAD'], cwd=ROOT, text=True).strip(),
        'preservedCubeCommit': PRESERVED_COMMIT,
        'preservedCubeIds': list(PRESERVED_IDS),
        'generator': {'name': 'build_android_presets.py', 'version': 2,
                      'sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                      'python': platform.python_version(),
                      'dependencies': {d: importlib.metadata.version(d) for d in ('spektrafilm', 'numpy', 'scipy', 'colour-science', 'numba', 'Pillow')}},
        'bakeSpec': {}, 'presets': [],
    }
    for record in records:
        cube = out / f'{record["id"]}.cube'
        if record['id'] in PRESERVED_IDS:
            if not cube.exists():
                raise FileNotFoundError(f'Preserved cube is missing: {cube}')
        elif not cube.exists():
            print(f'baking {record["id"]}', flush=True)
            _bake(record, out, cube)
            print(f'baked {record["id"]}', flush=True)
        spec = make_spec(record['id'])
        manifest['bakeSpec'][record['id']] = asdict(spec)
        manifest['presets'].append({
            'id': record['id'], 'displayName': record['display_name'], 'assetPath': f'presets/{cube.name}',
            'sha256': _sha256(cube), 'filmProfile': record['id'], 'printProfile': record['print_profile'],
            'scanFilm': record['scan_film'], 'inputColorSpace': 'sRGB', 'outputColorSpace': 'sRGB', 'resolution': 33,
            'domainMin': [0.0, 0.0, 0.0], 'domainMax': [1.0, 1.0, 1.0], 'attribution': ATTRIBUTION,
        })
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    shutil.copyfile(ROOT / 'SPEKTRAFILM_LICENSE.txt', out / 'LICENSE.txt')
    (out / 'CHANGELOG.txt').write_text(
        'Android v2 generated assets, schema 1\n' + ATTRIBUTION + '\n'
        'Generated/modified artifact: 33^3 sRGB-to-sRGB film LUTs for every FilmStocks camera stock.\n'
        'Portra 400, Gold 200, and Ektar 100 cube bytes are preserved from ' + PRESERVED_COMMIT + '.\n'
        'Other negatives and cine stocks use each profile target_print. Reversal stocks are scanned;\n'
        'their BundleSpec names kodak_portra_endura only as an unused carrier profile.\n'
        'Explicit native SDR headroom (stops_above_midgray=None); no automatic, spatial or stochastic effects.\n'
        'Full effective settings, source commit and dependency versions: manifest.json.\n'
        'The project source uses GPLv3; this directory preserves the separate asset license verbatim in LICENSE.txt.\n')
    return manifest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    build(parser.parse_args().out)
